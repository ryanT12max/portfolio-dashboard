-- 010_create_rent_estimate_attempt_audit.sql
--
-- Purpose:
--   Preserve the outcome of every RentCast enrichment attempt.  This lets the
--   backfill distinguish an address with no usable provider estimate from a
--   listing that has not yet been attempted, without repeatedly spending API
--   requests on known-unavailable listings.
--
-- Run once while connected as PORTFOLIO_APP in Oracle Database Actions.

CREATE TABLE re_rent_estimate_attempt (
    rent_estimate_attempt_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    property_key              NUMBER NOT NULL,
    run_id                    NUMBER NOT NULL,
    attempted_at              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    estimator_source          VARCHAR2(30) NOT NULL,
    requested_scope           VARCHAR2(20) NOT NULL,
    input_method              VARCHAR2(20) NOT NULL,
    attempt_status            VARCHAR2(30) NOT NULL,
    provider_http_status      NUMBER(3),
    error_category            VARCHAR2(50),
    error_message             VARCHAR2(1000),
    source_payload_hash       VARCHAR2(64),
    CONSTRAINT pk_re_rent_estimate_attempt
        PRIMARY KEY (rent_estimate_attempt_id),
    CONSTRAINT fk_re_rent_attempt_property
        FOREIGN KEY (property_key) REFERENCES re_property (property_key),
    CONSTRAINT fk_re_rent_attempt_run
        FOREIGN KEY (run_id) REFERENCES re_etl_run (run_id),
    CONSTRAINT uq_re_rent_attempt_run_property
        UNIQUE (run_id, property_key),
    CONSTRAINT ck_re_rent_attempt_scope
        CHECK (requested_scope IN ('PROPERTY', 'UNIT')),
    CONSTRAINT ck_re_rent_attempt_input
        CHECK (input_method IN ('ADDRESS', 'COORDINATES')),
    CONSTRAINT ck_re_rent_attempt_status
        CHECK (attempt_status IN ('ESTIMATED', 'UNAVAILABLE', 'TRANSIENT_FAILURE')),
    CONSTRAINT ck_re_rent_attempt_http_status
        CHECK (provider_http_status IS NULL OR provider_http_status BETWEEN 100 AND 599)
);

CREATE INDEX ix_re_rent_attempt_property_observed
    ON re_rent_estimate_attempt (property_key, attempted_at DESC);

CREATE INDEX ix_re_rent_attempt_status
    ON re_rent_estimate_attempt (attempt_status, estimator_source);