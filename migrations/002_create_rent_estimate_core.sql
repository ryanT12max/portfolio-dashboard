--
-- Purpose:
--   Add a historical rent-estimate model to the PORTFOLIO_APP canonical schema.
--
-- Safety:
--   This migration only creates new PORTFOLIO_APP objects. It does not alter
--   existing tables, views, or the legacy ADMIN-owned schema.
--
-- Run once while connected as PORTFOLIO_APP in Oracle Database Actions.

CREATE TABLE re_rent_estimate_snapshot (
    rent_estimate_snapshot_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    property_key               NUMBER NOT NULL,
    run_id                     NUMBER NOT NULL,
    observed_at                TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    estimator_source           VARCHAR2(30) NOT NULL,
    estimate_scope             VARCHAR2(20) NOT NULL,
    input_method               VARCHAR2(20) NOT NULL,
    estimated_monthly_rent     NUMBER(12,2) NOT NULL,
    rent_range_low             NUMBER(12,2),
    rent_range_high            NUMBER(12,2),
    comparable_count           NUMBER(3),
    source_payload_hash        VARCHAR2(64),
    CONSTRAINT pk_re_rent_estimate_snapshot
        PRIMARY KEY (rent_estimate_snapshot_id),
    CONSTRAINT fk_re_rent_snapshot_property
        FOREIGN KEY (property_key) REFERENCES re_property (property_key),
    CONSTRAINT fk_re_rent_snapshot_run
        FOREIGN KEY (run_id) REFERENCES re_etl_run (run_id),
    CONSTRAINT uq_re_rent_snapshot_run_property
        UNIQUE (run_id, property_key),
    CONSTRAINT ck_re_rent_snapshot_scope
        CHECK (estimate_scope IN ('PROPERTY', 'UNIT')),
    CONSTRAINT ck_re_rent_snapshot_input
        CHECK (input_method IN ('ADDRESS', 'COORDINATES')),
    CONSTRAINT ck_re_rent_snapshot_estimate
        CHECK (estimated_monthly_rent > 0),
    CONSTRAINT ck_re_rent_snapshot_range
        CHECK (
            (rent_range_low IS NULL OR rent_range_low > 0)
            AND (rent_range_high IS NULL OR rent_range_high > 0)
            AND (rent_range_low IS NULL OR rent_range_high IS NULL OR rent_range_low <= rent_range_high)
            AND (rent_range_low IS NULL OR rent_range_low <= estimated_monthly_rent)
            AND (rent_range_high IS NULL OR estimated_monthly_rent <= rent_range_high)
        ),
    CONSTRAINT ck_re_rent_snapshot_comps
        CHECK (comparable_count IS NULL OR comparable_count >= 0)
);

CREATE INDEX ix_re_rent_snapshot_prop_obs
    ON re_rent_estimate_snapshot (property_key, observed_at DESC);

CREATE INDEX ix_re_rent_snapshot_run
    ON re_rent_estimate_snapshot (run_id);

CREATE OR REPLACE VIEW vw_re_current_rent_estimate AS
    WITH ranked_estimates AS (
        SELECT
            e.rent_estimate_snapshot_id,
            e.property_key,
            e.run_id,
            e.observed_at,
            e.estimator_source,
            e.estimate_scope,
            e.input_method,
            e.estimated_monthly_rent,
            e.rent_range_low,
            e.rent_range_high,
            e.comparable_count,
            ROW_NUMBER() OVER (
                PARTITION BY e.property_key
                ORDER BY e.observed_at DESC, e.rent_estimate_snapshot_id DESC
            ) AS row_rank
        FROM re_rent_estimate_snapshot e
    )
    SELECT
        rent_estimate_snapshot_id,
        property_key,
        run_id,
        observed_at,
        estimator_source,
        estimate_scope,
        input_method,
        estimated_monthly_rent,
        rent_range_low,
        rent_range_high,
        comparable_count
    FROM ranked_estimates
    WHERE row_rank = 1;

COMMENT ON TABLE re_rent_estimate_snapshot IS
    'Historical provider rent estimates. Estimate scope distinguishes whole-property and single-unit values.';

COMMENT ON COLUMN re_rent_estimate_snapshot.estimate_scope IS
    'PROPERTY means an estimate for the whole property; UNIT means a single-unit estimate and must not be treated as whole-building income.';