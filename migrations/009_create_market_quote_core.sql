-- 009_create_market_quote_core.sql
--
-- Purpose:
--   Add a canonical, timestamped quote-snapshot model for market data that is
--   not an end-of-day close. This keeps real-time provider quotes separate
--   from MK_DAILY_PRICE, which is reserved for actual daily closing prices.
--
-- Run once while connected as PORTFOLIO_APP in Oracle Database Actions.
--
-- Safety:
--   This migration creates new PORTFOLIO_APP objects only. It does not alter
--   existing market tables, reporting views, or legacy ADMIN-owned objects.

CREATE TABLE mk_quote_snapshot (
    quote_snapshot_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    security_key        NUMBER NOT NULL,
    run_id              NUMBER NOT NULL,
    observed_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    provider_quote_at   TIMESTAMP WITH TIME ZONE,
    source_name         VARCHAR2(50) NOT NULL,
    current_price       NUMBER(18,6) NOT NULL,
    prior_close_price   NUMBER(18,6),
    change_amount       NUMBER(18,6),
    change_pct          NUMBER(12,6),
    day_open_price      NUMBER(18,6),
    day_high_price      NUMBER(18,6),
    day_low_price       NUMBER(18,6),
    source_payload_hash VARCHAR2(64) NOT NULL,
    CONSTRAINT pk_mk_quote_snapshot
        PRIMARY KEY (quote_snapshot_id),
    CONSTRAINT fk_mk_quote_snapshot_sec
        FOREIGN KEY (security_key) REFERENCES mk_security (security_key),
    CONSTRAINT fk_mk_quote_snapshot_run
        FOREIGN KEY (run_id) REFERENCES mk_etl_run (run_id),
    CONSTRAINT uq_mk_quote_run_security
        UNIQUE (run_id, security_key),
    CONSTRAINT ck_mk_quote_current_price
        CHECK (current_price > 0),
    CONSTRAINT ck_mk_quote_prior_close
        CHECK (prior_close_price IS NULL OR prior_close_price > 0),
    CONSTRAINT ck_mk_quote_day_open
        CHECK (day_open_price IS NULL OR day_open_price > 0),
    CONSTRAINT ck_mk_quote_day_high
        CHECK (day_high_price IS NULL OR day_high_price > 0),
    CONSTRAINT ck_mk_quote_day_low
        CHECK (day_low_price IS NULL OR day_low_price > 0),
    CONSTRAINT ck_mk_quote_day_range
        CHECK (
            day_low_price IS NULL
            OR day_high_price IS NULL
            OR day_low_price <= day_high_price
        )
);

CREATE INDEX ix_mk_quote_sec_provider_at
    ON mk_quote_snapshot (security_key, provider_quote_at DESC, quote_snapshot_id DESC);

CREATE INDEX ix_mk_quote_run
    ON mk_quote_snapshot (run_id);

CREATE OR REPLACE VIEW vw_mk_current_quote AS
    WITH ranked_quotes AS (
        SELECT
            q.quote_snapshot_id,
            q.security_key,
            q.run_id,
            q.observed_at,
            q.provider_quote_at,
            q.source_name,
            q.current_price,
            q.prior_close_price,
            q.change_amount,
            q.change_pct,
            q.day_open_price,
            q.day_high_price,
            q.day_low_price,
            ROW_NUMBER() OVER (
                PARTITION BY q.security_key
                ORDER BY
                    q.provider_quote_at DESC NULLS LAST,
                    q.observed_at DESC,
                    q.quote_snapshot_id DESC
            ) AS row_rank
        FROM mk_quote_snapshot q
        JOIN mk_etl_run run_audit
            ON run_audit.run_id = q.run_id
           AND run_audit.run_status IN ('SUCCEEDED', 'PARTIAL')
    )
    SELECT
        r.quote_snapshot_id,
        r.security_key,
        s.ticker,
        s.sector,
        r.run_id,
        r.observed_at,
        r.provider_quote_at,
        r.source_name,
        r.current_price,
        r.prior_close_price,
        r.change_amount,
        r.change_pct,
        r.day_open_price,
        r.day_high_price,
        r.day_low_price
    FROM ranked_quotes r
    JOIN mk_security s
        ON s.security_key = r.security_key
    WHERE r.row_rank = 1;
