-- 004_create_market_research_core.sql
--
-- Purpose:
--   Create the PORTFOLIO_APP canonical market-research model. This model
--   supports a stock-market watchlist and price-history analysis without
--   representing personal stock ownership.
--
-- Safety:
--   This migration creates new PORTFOLIO_APP objects only. It does not read,
--   alter, move, or delete the legacy ADMIN tables.
--
-- Run once while connected as PORTFOLIO_APP in Oracle Database Actions.

CREATE TABLE mk_etl_run (
    run_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    source_name         VARCHAR2(50) NOT NULL,
    started_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at        TIMESTAMP WITH TIME ZONE,
    run_status          VARCHAR2(20) NOT NULL,
    extracted_count     NUMBER(10) DEFAULT 0 NOT NULL,
    validated_count     NUMBER(10) DEFAULT 0 NOT NULL,
    rejected_count      NUMBER(10) DEFAULT 0 NOT NULL,
    loaded_count        NUMBER(10) DEFAULT 0 NOT NULL,
    error_message       VARCHAR2(1000),
    CONSTRAINT pk_mk_etl_run PRIMARY KEY (run_id),
    CONSTRAINT ck_mk_etl_run_status
        CHECK (run_status IN ('RUNNING', 'SUCCEEDED', 'FAILED', 'PARTIAL')),
    CONSTRAINT ck_mk_etl_run_counts
        CHECK (
            extracted_count >= 0
            AND validated_count >= 0
            AND rejected_count >= 0
            AND loaded_count >= 0
        )
);

CREATE TABLE mk_security (
    security_key        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ticker              VARCHAR2(10) NOT NULL,
    sector              VARCHAR2(50),
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_mk_security PRIMARY KEY (security_key),
    CONSTRAINT uq_mk_security_ticker UNIQUE (ticker)
);

CREATE TABLE mk_fundamental_snapshot (
    fundamental_snapshot_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    security_key             NUMBER NOT NULL,
    run_id                   NUMBER NOT NULL,
    source_name              VARCHAR2(50) NOT NULL,
    source_as_of_date        DATE,
    observed_at              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    market_price             NUMBER(18,6),
    pe_ratio                 NUMBER(18,6),
    peg_ratio                NUMBER(18,6),
    pb_ratio                 NUMBER(18,6),
    earnings_per_share       NUMBER(18,6),
    return_on_equity_pct     NUMBER(18,6),
    profit_margin_pct        NUMBER(18,6),
    debt_to_equity_ratio     NUMBER(18,6),
    free_cash_flow_value     NUMBER(24,6),
    free_cash_flow_unit      VARCHAR2(30),
    source_payload_hash      VARCHAR2(64),
    CONSTRAINT pk_mk_fundamental_snapshot
        PRIMARY KEY (fundamental_snapshot_id),
    CONSTRAINT fk_mk_fundamental_security
        FOREIGN KEY (security_key) REFERENCES mk_security (security_key),
    CONSTRAINT fk_mk_fundamental_run
        FOREIGN KEY (run_id) REFERENCES mk_etl_run (run_id),
    CONSTRAINT uq_mk_fundamental_run_security
        UNIQUE (run_id, security_key),
    CONSTRAINT ck_mk_fundamental_market_price
        CHECK (market_price IS NULL OR market_price > 0)
);

CREATE TABLE mk_daily_price (
    security_key        NUMBER NOT NULL,
    trade_date          DATE NOT NULL,
    run_id              NUMBER NOT NULL,
    source_name         VARCHAR2(50) NOT NULL,
    close_price         NUMBER(18,6) NOT NULL,
    volume              NUMBER(20) NOT NULL,
    observed_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_mk_daily_price PRIMARY KEY (security_key, trade_date),
    CONSTRAINT fk_mk_price_security
        FOREIGN KEY (security_key) REFERENCES mk_security (security_key),
    CONSTRAINT fk_mk_price_run
        FOREIGN KEY (run_id) REFERENCES mk_etl_run (run_id),
    CONSTRAINT ck_mk_daily_price_close
        CHECK (close_price > 0),
    CONSTRAINT ck_mk_daily_price_volume
        CHECK (volume >= 0)
);

CREATE INDEX ix_mk_fundamental_security_observed
    ON mk_fundamental_snapshot (security_key, observed_at DESC);

CREATE INDEX ix_mk_daily_price_trade_security
    ON mk_daily_price (trade_date, security_key);